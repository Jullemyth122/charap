const fs = require('fs');
const path = require('path');

// Read .env file
const envPath = path.join(__dirname, '.env');
let elevenlabsApiKey = '';
let geminiApiKey = '';

if (fs.existsSync(envPath)) {
  const envContent = fs.readFileSync(envPath, 'utf8');
  
  const elevenMatch = envContent.match(/ELEVENLABS_API_KEY\s*=\s*([^\r\n]+)/);
  if (elevenMatch) {
    elevenlabsApiKey = elevenMatch[1].trim();
  }

  const geminiMatch = envContent.match(/GEMINI_API_KEY\s*=\s*([^\r\n]+)/);
  if (geminiMatch) {
    geminiApiKey = geminiMatch[1].trim();
  }
}

// Generate environments directory if it doesn't exist
const envDir = path.join(__dirname, 'src', 'environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

// Write environment.ts
const content = `// This file is auto-generated by generate-env.js
export const environment = {
  production: false,
  elevenlabsApiKey: '${elevenlabsApiKey}',
  geminiApiKey: '${geminiApiKey}'
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), content, 'utf8');
console.log('Generated src/environments/environment.ts successfully with Gemini and ElevenLabs keys.');
